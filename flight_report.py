def _export_param_file(results_by_key: dict, report_path: str):
    """Export a unified .param with every suggestion analyzers agree on.

    Conflicting parameters are listed as comments, not written: this file
    goes onto an aircraft, and choosing between them takes a person.
    """
    merged, conflicts = merge_suggestions(list(results_by_key.values()))
    if not merged and not conflicts:
        return

    param_path = os.path.splitext(report_path)[0] + ".param"
    with open(param_path, "w", encoding="utf-8") as f:
        f.write("# Auto-generated by ArduScope\n")
        f.write(f"# Source: {os.path.basename(report_path)}\n")
        for c in conflicts:
            values = ", ".join(f"{e['source']}={e['value']}"
                               for e in distinct_values(c))
            f.write(f"# CONFLICT, not written: {c['param']}: {values}\n")
        for s in merged:
            suggested = s.get("suggested", "")
            if suggested not in (None, "", "-"):
                f.write(f"{s['param']},{suggested}\n")
    print(f"      {t('cli.param_file', path=param_path, count=len(merged))}")


def _analyzer_keys(option_value: str | None) -> set[str] | None:
    """Parse a comma-separated --only/--skip value."""
    if not option_value:
        return None
    return {key.strip() for key in option_value.split(',') if key.strip()}


def build_output_path(logfile: str, output: str | None,
                      fmt: str = "html") -> str:
    """Determine the output file path."""
    if output:
        return output
    base = os.path.splitext(os.path.basename(logfile))[0]
    log_dir = os.path.dirname(os.path.abspath(logfile))
    ext = fmt if fmt in ("csv", "json", "pdf") else "html"
    return os.path.join(log_dir, f"{base}_report.{ext}")


def _json_entry(r: AnalysisResult) -> dict:
    """One analyzer or sub-result as a JSON object."""
    entry = {
        "registry_key": r.registry_key,
        "title": r.title,
        "status": r.status,
        "failed": r.failed,
        "summary": r.summary,
        "details": [_strip_html(d) for d in r.details],
        "evidence_source": r.evidence_source,
        "action_level": r.action_level,
        "action_text": r.action_text,
    }
    if r.param_suggestions:
        entry["param_suggestions"] = r.param_suggestions
    if r.sub_results:
        entry["sub_results"] = [_json_entry(sub) for sub in r.sub_results]
    return entry


def export_json(results: list[AnalysisResult], vehicle_info,
                reader: LogReader, health_score: int,
                output_path: str, conflicts: list[dict]):
    """Export analysis results as JSON."""
    data = {
        "vehicle": {
            "type": vehicle_info.vehicle_type,
            "board": vehicle_info.board_name,
            "firmware": vehicle_info.firmware_version,
            "motors": vehicle_info.motor_count,
            "imus": vehicle_info.imu_count,
        },
        "flight": {
            "duration_s": reader.get_flight_duration(),
            "params_count": len(reader.params),
            "error_count": len(reader.errors),
        },
        "health_score": health_score,
        "analyzers": [_json_entry(r) for r in results],
        "conflicts": conflicts,
    }

    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)


def _strip_html(text: str) -> str:
    """Strip HTML tags and entities for plain-text export."""
    import html as _html
    text = re.sub(r'<[^>]+>', ' ', text)
    text = _html.unescape(text)   # handles &quot; &apos; &amp; &#xxx; etc.
    text = text.replace('\xa0', ' ')  # normalize non-breaking space from &nbsp;
    return re.sub(r' {2,}', ' ', text).strip()


def _csv_row(r: AnalysisResult, title: str) -> list[str]:
    """One analyzer or sub-result as a CSV row."""
    return [
        title, r.status, r.summary,
        " | ".join(_strip_html(d) for d in r.details),
        r.evidence_source, r.action_level,
        " | ".join(f"{s['param']}={s['suggested']}"
                   for s in r.param_suggestions),
    ]


def export_csv(results: list[AnalysisResult], vehicle_info,
               reader: LogReader, health_score: int,
               output_path: str, conflicts: list[dict]):
    """Export analysis results as CSV."""
    with open(output_path, 'w', newline='', encoding='utf-8-sig') as f:
        writer = SafeWriter(f)
        writer.writerow([t("csv.col_analyzer"), t("csv.col_status"),
                         t("csv.col_summary"), t("csv.col_details"),
                         t("csv.col_evidence"), t("csv.col_action"),
                         t("csv.col_params")])
        for r in results:
            writer.writerow(_csv_row(r, r.title))
            for sub in r.sub_results:
                writer.writerow(_csv_row(sub, f"{r.title}/{sub.title}"))
        writer.writerow([])
        writer.writerow([t("csv.meta_score"), health_score])
        writer.writerow([t("csv.meta_vehicle"), vehicle_info.vehicle_type])
        writer.writerow([t("csv.meta_board"), vehicle_info.board_name])
        writer.writerow([t("csv.meta_firmware"), vehicle_info.firmware_version])
        writer.writerow([t("csv.meta_duration"), f"{reader.get_flight_duration():.1f}"])
        for c in conflicts:
            writer.writerow([
                t("csv.meta_conflict"), c["param"],
                " | ".join(f"{e['source']}={e['value']}"
                           for e in distinct_values(c))])


def main():
    parser = argparse.ArgumentParser(
        description="ArduScope flight log analysis report generator",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    parser.add_argument(
        "logfile",
        nargs="?",
        help="ArduPilot .BIN log file path",
    )
    parser.add_argument(
        "-o", "--output",
        help="Output file path (default: <logfile>_report.<format>)",
    )
    parser.add_argument(
        "--no-open",
        action="store_true",
        help="Do not open the report in a browser after generation",
    )
    parser.add_argument(
        "--skip",
        help="Comma-separated list of analyzer keys to skip",
    )
    parser.add_argument(
        "--only",
        help="Comma-separated list of analyzer keys to run (exclusive)",
    )
    parser.add_argument(
        "--format",
        choices=["html", "json", "csv", "pdf"],
        default="html",
        help="Output format (default: html)",
    )
    parser.add_argument(
        "--thresholds",
        help="JSON file with threshold overrides",
    )
    parser.add_argument(
        "--template",
        help="Scenario template (quadplane-accept, tuning-compare, "
             "crash-diagnosis, battery-aging, copter-factory)",
    )
    parser.add_argument(
        "--no-ai",
        action="store_true",
        help="Disable AI diagnosis report",
    )
    parser.add_argument(
        "--ai-provider",
        choices=["rule", "anthropic", "openai"],
        default="rule",
        help="Who writes the AI diagnosis (default: rule, the offline rule "
             "engine). anthropic and openai name the API an LLM is asked "
             "through, read their key from ANTHROPIC_API_KEY / "
             "OPENAI_API_KEY and need --ai-model",
    )
    parser.add_argument(
        "--ai-model",
        metavar="NAME",
        help="Model the LLM diagnosis asks for. No name is built in",
    )
    parser.add_argument(
        "--ai-base-url",
        metavar="URL",
        help="Where the API is, for a service other than the provider's "
             "own that speaks the same API. The key goes to this address",
    )
    # Kept only to refuse it with an explanation, see below.
    parser.add_argument("--ai-key", help=argparse.SUPPRESS)
    parser.add_argument(
        "--trace-points",
        type=int,
        default=2000,
        help="Max data points per Plotly trace (default: 2000)",
    )
    parser.add_argument(
        "--no-map",
        action="store_true",
        help="Disable GPS map in HTML report",
    )
    parser.add_argument(
        "--no-fleet-record",
        action="store_true",
        help="Do not archive this flight into the fleet history db "
             "(fleet.db next to the report)",
    )
    parser.add_argument(
        "--lang",
        choices=["zh", "en"],
        default="zh",
        help="Report language (default: zh)",
    )
    parser.add_argument(
        "--list-templates",
        action="store_true",
        help="List available scenario templates and exit",
    )
    args = parser.parse_args()

    set_locale(args.lang)

    # Handle --list-templates
    if args.list_templates:
        print(t("cli.available_templates"))
        for tpl in list_templates():
            print(f"  {tpl.name:25s} {tpl.display_name}")
            print(f"  {'':25s} {tpl.description}")
        sys.exit(0)

    # Validate arguments first (before I/O) so that typos in option
    # values are reported even when the logfile is also wrong.
    if args.ai_key:
        print(t("cli.err_ai_key_argv",
                env="ANTHROPIC_API_KEY / OPENAI_API_KEY"), file=sys.stderr)
        sys.exit(1)
    if args.ai_provider == "rule":
        # An option that changes nothing is a typo or a wrong belief about
        # what will happen to the report.
        for option, value in (("--ai-model", args.ai_model),
                              ("--ai-base-url", args.ai_base_url)):
            if value is not None:
                print(t("cli.err_ai_option_without_provider", option=option),
                      file=sys.stderr)
                sys.exit(1)
    else:
        if not args.ai_model:
            print(t("cli.err_ai_model_missing", provider=args.ai_provider),
                  file=sys.stderr)
            sys.exit(1)
        if args.ai_base_url is not None and not args.ai_base_url.startswith(
                ("http://", "https://")):
            print(t("cli.err_ai_base_url", url=args.ai_base_url),
                  file=sys.stderr)
            sys.exit(1)

    template = None
    if args.template:
        template = get_template(args.template)
        if template is None:
            print(t("cli.err_unknown_template", name=args.template), file=sys.stderr)
            print(t("cli.err_list_templates"))
            sys.exit(1)

    skip_set = _analyzer_keys(args.skip)
    only_set = _analyzer_keys(args.only)
    known = {key for key, _cls in discover_analyzers()}
    unknown = ((skip_set or set()) | (only_set or set())) - known
    if unknown:
        print(t("cli.err_unknown_analyzer", keys=", ".join(sorted(unknown)),
                known=", ".join(sorted(known))), file=sys.stderr)
        sys.exit(1)

    if args.thresholds:
        try:
            Thresholds().load_overrides(args.thresholds)
        except ValueError as e:
            print(f"  {e}", file=sys.stderr)
            sys.exit(1)

    # Validate input
    if not args.logfile:
        parser.error("logfile is required")
    if not os.path.isfile(args.logfile):
        print(t("cli.err_file_not_found", path=args.logfile), file=sys.stderr)
        sys.exit(1)

    if template is not None:
        print(t("cli.template_using", name=template.display_name))

    if template and template.analyzers:
        if only_set:
            print(t("cli.note_template_overrides"), file=sys.stderr)
        only_set = set(template.analyzers)

    # Run unified pipeline
    print(f"{t('cli.stage_read')} {os.path.basename(args.logfile)} ...")
    try:
        pipeline = run_analysis(
            args.logfile,
            template=template,
            only=only_set,
            skip=skip_set,
            thresholds_path=args.thresholds,
            include_gps=not args.no_map,
        )
    except (ValueError, FileNotFoundError) as e:
        print(f"  {e}", file=sys.stderr)
        sys.exit(1)
    except Exception as e:
        print(t("cli.err_parse", error=e), file=sys.stderr)
        sys.exit(1)

    reader = pipeline.reader
    vehicle_info = pipeline.vehicle_info
    results = pipeline.results
    results_by_key = pipeline.results_by_key
    health_score = pipeline.health_score
    param_conflicts = pipeline.conflicts
    gps_track = pipeline.gps_track

    print(t("cli.vehicle_info", vehicle=f"{vehicle_info.vehicle_type} {vehicle_info.firmware_version}"))
    print(t("cli.analyzer_count", count=len(results_by_key), score=health_score))
    if param_conflicts:
        print(t("cli.param_conflicts", count=len(param_conflicts)))

    # AI diagnosis (post-pipeline, CLI-specific)
    print(t('cli.stage_report'))
    if not args.no_ai and results_by_key:
        diagnosis = generate_diagnosis(
            results_by_key, vehicle_info, health_score,
            reader.get_flight_duration(),
            provider=args.ai_provider,
            model=args.ai_model or "",
            base_url=args.ai_base_url or "",
        )
        results.insert(0, diagnosis)
        print(t("cli.ai_diagnosis", provider=diagnosis.provider, summary=diagnosis.summary))

    # Step 5: Generate report
    output_path = build_output_path(args.logfile, args.output, args.format)
    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    print(f"{t('cli.stage_done')} {output_path} ...")

    # Fleet history: archive this flight (default on) and append the
    # per-airframe trend card when there is history to show. Archive
    # failures must never block the report.
    if not args.no_fleet_record:
        try:
            from lib import fleet_history
            db_path = os.path.join(
                os.path.dirname(os.path.abspath(output_path)), "fleet.db")
            serial, n = fleet_history.record(db_path, pipeline, args.logfile)
            print("      " + t("fleet.recorded_note", serial=serial, n=n))
            hist = fleet_history.build_history_result(
                fleet_history.query_history(db_path, serial), serial)
            if hist is not None:
                results.append(hist)
        except Exception as e:
            print(f"  [warn] fleet record failed: {e}", file=sys.stderr)

    if args.format == "json":
        export_json(results, vehicle_info, reader, health_score, output_path,
                    param_conflicts)
    elif args.format == "csv":
        export_csv(results, vehicle_info, reader, health_score, output_path,
                   param_conflicts)
    elif args.format == "pdf":
        try:
            from lib.pdf_export import html_to_pdf
        except ImportError:
            print(t('report.pdf_requires_weasyprint'), file=sys.stderr)
            sys.exit(1)
        generator = HtmlReportGenerator(
            vehicle_info=vehicle_info,
            results=results,
            log_filename=os.path.basename(args.logfile),
            flight_duration=reader.get_flight_duration(),
            health_score=health_score,
            gps_track=gps_track,
            max_trace_points=args.trace_points,
            static_images=True,
        )
        try:
            html_string = generator.generate()
        except ChartRenderError as e:
            print(t('report.pdf_chart_failed', detail=e), file=sys.stderr)
            sys.exit(1)
        try:
            html_to_pdf(html_string, output_path)
        except ImportError:
            print(t('report.pdf_requires_weasyprint'), file=sys.stderr)
            sys.exit(1)
        print(f"      {t('report.pdf_exported', path=output_path)}")
    else:
        generator = HtmlReportGenerator(
            vehicle_info=vehicle_info,
            results=results,
            log_filename=os.path.basename(args.logfile),
            flight_duration=reader.get_flight_duration(),
            health_score=health_score,
            gps_track=gps_track,
            max_trace_points=args.trace_points,
        )
        generator.write(output_path)

    file_size = os.path.getsize(output_path)
    print(t("cli.done_size", size=f"{file_size / 1024:.0f}"))

    # Export .param file if notch_tuning produced recommendations
    _export_param_file(results_by_key, output_path)

    # Open in browser (HTML only)
    if args.format == "html" and not args.no_open:
        from pathlib import Path
        url = Path(os.path.abspath(output_path)).as_uri()
        print(f"      Browser: {url}")
        webbrowser.open(url)
    elif args.no_open:
        print(f"      {t('cli.skipped_browser')}")


if __name__ == "__main__":
    main()
