"""
ArduScope Flight Log Analysis Report Generator.

Generates a standalone interactive HTML report from an ArduPilot .BIN log file.

Usage:
    python3 flight_report.py 00000285.BIN
    python3 flight_report.py -o report.html --no-open 00000285.BIN
    python3 flight_report.py --skip motor,vibration 00000285.BIN
    python3 flight_report.py --only summary,attitude 00000285.BIN
    python3 flight_report.py --format csv 00000285.BIN
    python3 flight_report.py --thresholds custom.json 00000285.BIN
"""

