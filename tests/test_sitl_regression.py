"""
SITL-based regression tests for ArduScope.

These tests validate ArduScope against SITL-generated .BIN logs with
known fault injections. Unlike SyntheticReader tests (which craft numpy
arrays), these exercise the full pipeline including pymavlink parsing,
message filtering, and cross-analyzer correlation.

Logs are generated by tests/sitl/generate_logs.py and stored in
tests/sitl/logs/. Tests skip cleanly when logs are absent, so they
work in both local and CI environments.

Run SITL log generation first:
    python3 tests/sitl/generate_logs.py

Then run these tests:
    python3 -m pytest tests/test_sitl_regression.py -v
"""

from __future__ import annotations

import functools
import json
import os

import pytest

pytestmark = pytest.mark.sitl

_SITL_DIR = os.path.join(os.path.dirname(__file__), "sitl")
_LOGS_DIR = os.path.join(_SITL_DIR, "logs")
_SCENARIOS_FILE = os.path.join(_SITL_DIR, "scenarios.json")


def _load_scenarios() -> list[dict]:
    with open(_SCENARIOS_FILE, encoding="utf-8") as f:
        return json.load(f)["scenarios"]


def _log_path(scenario_name: str) -> str:
    return os.path.join(_LOGS_DIR, f"{scenario_name}.BIN")


@functools.cache
def _run_pipeline(log_file: str):
    """Run the full ArduScope analysis pipeline on a log file, once."""
    from lib.pipeline import run_analysis
    return run_analysis(log_file)


_SCENARIOS = _load_scenarios()


def _scenario_ids():
    return [s["name"] for s in _SCENARIOS]


@pytest.fixture(params=_SCENARIOS, ids=_scenario_ids())
def scenario(request):
    s = request.param
    log = _log_path(s["name"])
    if not os.path.isfile(log):
        pytest.skip(f"SITL log not found: {log} (run tests/sitl/generate_logs.py)")
    s["_log_path"] = log
    return s


class TestSitlPipeline:
    """Validate ArduScope output against SITL scenarios with known faults."""

    def test_pipeline_completes(self, scenario):
        """The pipeline must not crash on any SITL-generated log."""
        result = _run_pipeline(scenario["_log_path"])
        assert result is not None
        assert len(result.results) > 0
        assert 0 <= result.health_score <= 100

    def test_vehicle_detection(self, scenario):
        """Vehicle type should match what SITL was configured to simulate."""
        result = _run_pipeline(scenario["_log_path"])
        expected_vehicle = scenario["vehicle"]
        assert expected_vehicle in result.vehicle_info.vehicle_type

    def test_health_score_range(self, scenario):
        """Health score should fall within expected range for the scenario."""
        expected = scenario.get("expected", {})
        min_score = expected.get("health_score_min")
        max_score = expected.get("health_score_max")
        if min_score is None and max_score is None:
            pytest.skip("No health score expectation for this scenario")
        result = _run_pipeline(scenario["_log_path"])
        if min_score is not None:
            assert result.health_score >= min_score, \
                f"Health score {result.health_score} < expected min {min_score}"
        if max_score is not None:
            assert result.health_score <= max_score, \
                f"Health score {result.health_score} > expected max {max_score}"

    def test_expected_good_analyzers(self, scenario):
        """Analyzers listed as 'good' should not be warning/critical."""
        expected = scenario.get("expected", {})
        good_keys = expected.get("analyzers_good", [])
        if not good_keys:
            pytest.skip("No 'analyzers_good' expectation")
        result = _run_pipeline(scenario["_log_path"])
        for key in good_keys:
            r = result.results_by_key.get(key)
            # The expectation file names this analyzer — its absence
            # (renamed key, broken discovery) must fail, not silently
            # retire the whole expectation.
            assert r is not None, \
                f"Expected analyzer '{key}' missing from results " \
                f"(renamed? discovery broken?)"
            assert r.status in ("good", "info"), \
                f"Expected {key} to be good/info but got {r.status}: {r.summary}"

    def test_expected_warning_or_critical(self, scenario):
        """Analyzers with injected faults should trigger warning/critical."""
        expected = scenario.get("expected", {})
        bad_keys = expected.get("analyzers_warning_or_critical", [])
        if not bad_keys:
            pytest.skip("No 'analyzers_warning_or_critical' expectation")
        result = _run_pipeline(scenario["_log_path"])
        for key in bad_keys:
            r = result.results_by_key.get(key)
            assert r is not None, \
                f"Expected analyzer '{key}' missing from results " \
                f"(renamed? discovery broken?)"
            assert r.status in ("warning", "critical"), \
                f"Expected {key} to fire but got {r.status}: {r.summary}"

    def test_expected_not_critical(self, scenario):
        """Analyzers listed should not reach critical severity."""
        expected = scenario.get("expected", {})
        not_critical_keys = expected.get("analyzers_not_critical", [])
        if not not_critical_keys:
            pytest.skip("No 'analyzers_not_critical' expectation")
        result = _run_pipeline(scenario["_log_path"])
        for key in not_critical_keys:
            r = result.results_by_key.get(key)
            assert r is not None, \
                f"Expected analyzer '{key}' missing from results " \
                f"(renamed? discovery broken?)"
            assert r.status != "critical", \
                f"Expected {key} NOT critical but got: {r.summary}"

    def test_cross_rules_fire(self, scenario):
        """Cross-correlation rules should fire for multi-fault scenarios."""
        expected = scenario.get("expected", {})
        expected_rules = expected.get("cross_rules_should_fire", [])
        if not expected_rules:
            pytest.skip("No cross-rule expectations")
        result = _run_pipeline(scenario["_log_path"])

        from lib.ai_diagnosis import _build_cross_rules, _match_cross_rules
        rules = {r.name: set(r.conditions) for r in _build_cross_rules()}
        fired = [set(m.related_keys)
                 for m in _match_cross_rules(result.results_by_key)]

        for rule_name in expected_rules:
            assert rule_name in rules, f"No cross-rule named '{rule_name}'"
            # A named expectation that doesn't fire is a FAILURE — the
            # old pytest.skip here kept the suite green even with all
            # 22 cross-rules dead. If SITL fault injection is too weak
            # for a rule, remove it from the scenario's expectation
            # file, don't soften the gate.
            assert rules[rule_name] in fired, (
                f"Cross-rule '{rule_name}' didn't fire. Fired: {fired}."
            )

    def test_expected_suggestions(self, scenario):
        """A flight with a known fault should get the advice for it."""
        wanted = scenario.get("expected", {}).get("suggestions_include", [])
        if not wanted:
            pytest.skip("No suggestion expectations")
        result = _run_pipeline(scenario["_log_path"])
        suggested = {s["param"] for r in result.results_by_key.values()
                     for s in r.param_suggestions}
        missing = set(wanted) - suggested
        assert not missing, f"Missing {missing}, got {sorted(suggested)}"

    def test_expected_suggestion_values(self, scenario):
        """Values the flight does not change, and ranges for those it does.

        A name alone let INS_HNTCH_MODE 3 ship without the INS_HNTCH_REF
        that makes it track.
        """
        expected = scenario.get("expected", {})
        equal = expected.get("suggestions_equal", {})
        between = expected.get("suggestions_between", {})
        if not equal and not between:
            pytest.skip("No suggestion value expectations")
        result = _run_pipeline(scenario["_log_path"])
        suggested = {s["param"]: s["suggested"]
                     for r in result.results_by_key.values()
                     for s in r.param_suggestions}
        assert {name: suggested.get(name) for name in equal} == equal
        for name, (low, high) in between.items():
            assert name in suggested, f"{name} not suggested"
            assert low <= suggested[name] <= high, \
                f"{name}={suggested[name]} outside {low} to {high}"

    def test_param_file_generation(self, scenario, tmp_path):
        """Every scenario runs the export, with or without suggestions.

        A flight that legitimately suggests nothing (plane_tecs_tuning:
        speed RMS 2.78 under the 3.0 warning line) checks the empty case
        instead of skipping. A skip made the gate's test count move with
        flight-to-flight variation and hid that the export had not run.
        """
        result = _run_pipeline(scenario["_log_path"])

        all_suggestions = []
        for r in result.results:
            all_suggestions.extend(r.param_suggestions)
            for sub in r.sub_results:
                all_suggestions.extend(sub.param_suggestions)

        from flight_report import _export_param_file
        out_html = tmp_path / "report.html"
        out_html.write_text("<html></html>")
        param_file = tmp_path / "report.param"

        if not all_suggestions:
            _export_param_file(result.results_by_key, str(out_html))
            assert not param_file.exists(), \
                "no suggestions, so no .param file may be written"
            return

        _export_param_file(result.results_by_key, str(out_html))
        assert param_file.exists()
        content = param_file.read_text()
        assert "Auto-generated" in content


class TestSitlVsSynthetic:
    """Compare SITL and SyntheticReader results for consistency."""

    def test_analyzer_count_matches(self, scenario):
        """SITL logs should activate at least as many analyzers as expected."""
        result = _run_pipeline(scenario["_log_path"])
        assert len(result.results) >= 5, \
            f"Only {len(result.results)} analyzers ran — expected at least 5 for a SITL log"

    def test_all_results_have_required_fields(self, scenario):
        """Every AnalysisResult must have title, status, summary."""
        result = _run_pipeline(scenario["_log_path"])
        for r in result.results:
            assert r.title, f"Missing title in result: {r}"
            assert r.status in ("good", "info", "warning", "critical"), \
                f"Invalid status '{r.status}' in {r.title}"
